"""The real-data experiment, as a function rather than a script.

Honesty rule 5: every number in the README and the reports comes from a cell
that ran, so the table is regenerated by `seattle_comparison()` and written
to `results/`, never typed.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from qphys.collapse import baselines as B
from qphys.collapse import causal_states as cs
from qphys.collapse import data as D
from qphys.collapse import processes as pr
from qphys.config import RESULTS_DIR


def seattle_comparison(
    hmm_restarts: int = 8,
    hqmm_restarts: int = 5,
    n_seeds: int = 5,
    save: bool = True,
) -> pd.DataFrame:
    """Every model on the same temporal split, at stated capacity, over seeds.

    Two things this function refuses to do, both learned the hard way here:

    **It does not report a single fit.** One hqmm-d3 fit reached 0.8464 bits,
    which at 17 free parameters beats every classical model costing 17 or
    fewer, and looked like a reversal of the headline. Over five seeds the
    same configuration averages 0.8785 +- 0.0267, while hmm-2 sits at 0.8551
    with a standard deviation of 9e-06. That 0.8464 was the favourable tail
    of a wide distribution. Honesty rule 6 is what caught it.

    **It does not under-tune the classical side.** Without restarts the HMM at
    k = 2 and k = 3 converges to a degenerate single-emission solution and
    returns exactly the i.i.d. likelihood, which would make the comparison
    unfair in the HQMM's favour.

    The deterministic models (i.i.d., Markov) are fitted once, since they have
    no seed dependence to average over, and their std is reported as 0.
    """
    series = D.seattle_wet_dry()
    train, test = D.temporal_split(series.values)

    rows = [B.fit_iid(train, test) | {"nll_std": 0.0, "n_seeds": 1}]
    rows += [
        B.fit_markov(train, test, order=o) | {"nll_std": 0.0, "n_seeds": 1}
        for o in (1, 2, 3, 4)
    ]

    per_seed: list[dict] = []

    def over_seeds(fn, **kw):
        vals = [fn(train, test, seed=100 * s, **kw) for s in range(n_seeds)]
        per_seed.extend(
            {"seed": s, "model": v["model"], "nll": v["nll"]}
            for s, v in enumerate(vals)
        )
        return vals[0] | {
            "nll": float(np.mean([v["nll"] for v in vals])),
            "nll_std": float(np.std([v["nll"] for v in vals], ddof=1)),
            "n_seeds": n_seeds,
        }

    rows += [over_seeds(B.fit_hmm, k=k, n_restarts=hmm_restarts) for k in (2, 3, 4)]
    rows += [over_seeds(B.fit_hqmm, d=d, n_restarts=hqmm_restarts) for d in (2, 3)]

    df = pd.DataFrame(rows)[["model", "params", "nll", "nll_std", "n_seeds"]]
    df["is_real_data"] = series.is_real
    if save:
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        df.to_csv(RESULTS_DIR / "seattle_table.csv", index=False)
        # the spread behind every seeded row, so a mean can be checked
        pd.DataFrame(per_seed).to_csv(RESULTS_DIR / "seattle_seeds.csv", index=False)
    return df


def best_at_or_below(df: pd.DataFrame, params: int) -> pd.Series:
    """The best classical model no more expensive than `params`.

    This is what "matched capacity" means operationally (honesty rule 3):
    a quantum model with 7 free parameters must beat everything classical
    that costs 7 or fewer, not merely beat the one-parameter baseline.
    """
    classical = df[~df.model.str.startswith("hqmm")]
    eligible = classical[classical.params <= params]
    return eligible.loc[eligible.nll.idxmin()]


def seattle_memory(save: bool = True) -> dict:
    """C_mu and C_q of the estimated order-1 chain: the REPRESENTATION result.

    This is a statement about an idealised construction from the estimated
    transition matrix. It is not a statement about prediction, and the two
    must never be conflated -- a 72% memory saving and a worse test NLL are
    both true at once and say different things.
    """
    series = D.seattle_wet_dry()
    t = pr.transition_matrix(series.values)
    out = {
        "transition": t.tolist(),
        "C_mu_bits": cs.c_mu(t),
        "C_q_bits": cs.c_q(t),
        "is_real_data": series.is_real,
    }
    out["saving_pct"] = 100.0 * (1.0 - out["C_q_bits"] / out["C_mu_bits"])
    if save:
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        pd.DataFrame([out]).to_json(
            RESULTS_DIR / "seattle_memory.json", orient="records"
        )
    return out


def symbolisation_sweep(methods=("median", "mean", "positive")) -> pd.DataFrame:
    """A result surviving only one symbolisation is not a result."""
    raw = D.load_csv_series("seattle-weather", "precipitation")
    rows = []
    for method in methods:
        bits = pr.symbolise(raw.values, method)
        train, test = D.temporal_split(bits)
        t = pr.transition_matrix(bits)
        rows.append(
            {
                "symbolisation": method,
                "wet_fraction": float(np.mean(bits)),
                "iid_nll": B.fit_iid(train, test)["nll"],
                "markov1_nll": B.fit_markov(train, test, order=1)["nll"],
                "C_mu": cs.c_mu(t),
                "C_q": cs.c_q(t),
            }
        )
    return pd.DataFrame(rows)
